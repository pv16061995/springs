document.addEventListener("DOMContentLoaded", function () {

    const modal = document.getElementById("imageModal");
    const modalImage = document.getElementById("modalImage");
    const closeBtn = document.getElementById("modalClose");
    const prevBtn = document.getElementById("modalPrev");
    const nextBtn = document.getElementById("modalNext");
    const counter = document.getElementById("modalCounter");

    const gallery = document.getElementById("gallery");

    let currentIndex = 0;
    let visibleImages = [];

    function updateImages() {
        visibleImages = Array.from(
            gallery.querySelectorAll(".gallery-item")
        ).filter(item => !item.classList.contains("hidden"));
    }

    function showImage(index) {
        updateImages();

        if (!visibleImages.length) return;

        currentIndex =
            (index + visibleImages.length) % visibleImages.length;

        const item = visibleImages[currentIndex];
        const image = item.querySelector("img");

        // Use the full-size image from href
        modalImage.src = item.getAttribute("href") || image.src;
        modalImage.alt = image.alt || "Gallery image";

        counter.textContent =
            (currentIndex + 1) + " / " + visibleImages.length;

        modal.classList.add("show");
        document.body.style.overflow = "hidden";
    }

    gallery.addEventListener("click", function (event) {
        const item = event.target.closest(".gallery-item");

        if (!item) return;

        event.preventDefault();

        updateImages();
        showImage(visibleImages.indexOf(item));
    });

    prevBtn.addEventListener("click", function () {
        showImage(currentIndex - 1);
    });

    nextBtn.addEventListener("click", function () {
        showImage(currentIndex + 1);
    });

    function closeModal() {
        modal.classList.remove("show");
        modalImage.src = "";
        document.body.style.overflow = "";
    }

    closeBtn.addEventListener("click", closeModal);

    // Close when clicking the dark background
    modal.addEventListener("click", function (event) {
        if (event.target === modal) {
            closeModal();
        }
    });

    // Keyboard navigation
    document.addEventListener("keydown", function (event) {
        if (!modal.classList.contains("show")) return;

        if (event.key === "Escape") closeModal();
        if (event.key === "ArrowLeft") showImage(currentIndex - 1);
        if (event.key === "ArrowRight") showImage(currentIndex + 1);
    });

});

document.addEventListener("DOMContentLoaded", function () {

    const filterButtons = document.querySelectorAll(".filter-btn");
    const galleryItems = document.querySelectorAll(".gallery-item");

    filterButtons.forEach(function (button) {

        button.addEventListener("click", function () {

            // Get selected category
            const filterValue = this.getAttribute("data-filter");

            // Remove active class from all buttons
            filterButtons.forEach(function (btn) {
                btn.classList.remove("active");
            });

            // Add active class to clicked button
            this.classList.add("active");

            // Show or hide gallery images
            galleryItems.forEach(function (item) {

                const category = item.getAttribute("data-category");

                if (filterValue === "all" || category === filterValue) {
                    item.classList.remove("hidden");
                } else {
                    item.classList.add("hidden");
                }

            });

        });

    });

});

